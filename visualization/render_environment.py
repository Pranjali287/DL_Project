"""
2D Visualization and Rendering Engine for GRAIL-NAV.
Visualizes grid boundaries, start/goal locations, obstacle layouts,
and exact trajectory paths generated by the trained DQN policy.
"""

from pathlib import Path
from typing import List, Optional, Tuple
import matplotlib.patches as patches
import matplotlib.pyplot as plt
import numpy as np

from agent.dqn_agent import DQNAgent
from config import DEFAULT_ENV_CONFIG, EnvConfig, RESULTS_DIR
from environment.grid_world import GridWorldEnv

TRAJECTORY_DIR = RESULTS_DIR / "plots"
TRAJECTORY_DIR.mkdir(parents=True, exist_ok=True)


def render_navigation_episode(
    model_path: Path,
    seed: int = 9005,
    scenario_label: str = "Unseen Test Map",
    env_config: Optional[EnvConfig] = None,
    save_path: Optional[Path] = None,
    show_gui: bool = False
) -> Tuple[Path, bool, int, float]:
    """
    Simulate one episode under the trained policy and render the 2D grid trajectory.
    """
    env_cfg = env_config or DEFAULT_ENV_CONFIG
    env = GridWorldEnv(config=env_cfg)

    agent = DQNAgent(state_dim=env.state_dim, action_dim=env.config.action_dim)
    agent.load(model_path)

    # Reset environment
    state, _ = env.reset(seed=seed)
    terminated = False
    truncated = False
    ep_reward = 0.0

    # Execute deterministic greedy DQN trajectory
    while not (terminated or truncated):
        action = agent.act(state, eval_mode=True)
        state, reward, terminated, truncated, info = env.step(action)
        ep_reward += reward

    trajectory = env.trajectory
    grid = env.grid
    grid_size = env.grid_size
    success = info.get("success", False)
    collision = info.get("collision", False)
    steps = info.get("step_count", len(trajectory) - 1)

    # Plot 2D Grid Environment
    fig, ax = plt.subplots(figsize=(8, 8))
    ax.set_xlim(-0.5, grid_size - 0.5)
    ax.set_ylim(-0.5, grid_size - 0.5)
    ax.set_aspect("equal")
    ax.invert_yaxis()  # Match matrix row indexing (0 at top)

    # Draw grid lines
    for i in range(grid_size + 1):
        ax.axhline(i - 0.5, color="#cfd8dc", linewidth=1.0, linestyle="-")
        ax.axvline(i - 0.5, color="#cfd8dc", linewidth=1.0, linestyle="-")

    # Draw obstacles
    for r in range(grid_size):
        for c in range(grid_size):
            if grid[r, c] == 1:
                rect = patches.Rectangle(
                    (c - 0.5, r - 0.5), 1, 1,
                    facecolor="#37474f",
                    edgecolor="#263238",
                    linewidth=1.2
                )
                ax.add_patch(rect)

    # Draw Start cell (0, 0)
    sr, sc = env.start_pos
    start_patch = patches.Rectangle(
        (sc - 0.45, sr - 0.45), 0.9, 0.9,
        facecolor="#c8e6c9",
        edgecolor="#2e7d32",
        linewidth=2,
        linestyle="--"
    )
    ax.add_patch(start_patch)
    ax.text(sc, sr, "START\n(0,0)", ha="center", va="center", color="#1b5e20", fontsize=9, fontweight="bold")

    # Draw Goal cell (9, 9)
    gr, gc = env.goal_pos
    goal_patch = patches.Rectangle(
        (gc - 0.45, gr - 0.45), 0.9, 0.9,
        facecolor="#ffcdd2",
        edgecolor="#c62828",
        linewidth=2
    )
    ax.add_patch(goal_patch)
    ax.text(gc, gr, "GOAL\n(9,9)", ha="center", va="center", color="#b71c1c", fontsize=9, fontweight="bold")

    # Draw Trajectory
    if len(trajectory) > 1:
        traj_cols = [p[1] for p in trajectory]
        traj_rows = [p[0] for p in trajectory]

        # Draw trajectory line
        ax.plot(traj_cols, traj_rows, color="#0288d1", linewidth=3.0, alpha=0.85, zorder=4)

        # Draw arrows along steps
        for i in range(len(trajectory) - 1):
            r1, c1 = trajectory[i]
            r2, c2 = trajectory[i + 1]
            ax.annotate(
                "",
                xy=(c2, r2),
                xytext=(c1, r1),
                arrowprops=dict(
                    arrowstyle="->",
                    color="#01579b",
                    lw=2.0,
                    shrinkA=4,
                    shrinkB=4
                ),
                zorder=5
            )

        # Draw waypoint markers
        for step_idx, (r, c) in enumerate(trajectory):
            ax.scatter(c, r, color="#ffffff", edgecolor="#01579b", s=60, linewidth=1.5, zorder=6)

    # Final Outcome Annotation
    status_str = "SUCCESS (Goal Reached)" if success else ("COLLISION" if collision else "TIMEOUT")
    status_color = "#2e7d32" if success else ("#c62828" if collision else "#ef6c00")

    final_r, final_c = trajectory[-1]
    ax.scatter(
        final_c, final_r,
        marker="X" if collision else ("*" if success else "o"),
        s=250,
        color=status_color,
        edgecolor="black",
        linewidth=1.5,
        zorder=7
    )

    ax.set_title(
        f"GRAIL-NAV DQN Navigation Trajectory\n"
        f"Scenario: {scenario_label} (Seed: {seed}) | Status: {status_str}\n"
        f"Steps Taken: {steps} | Cumulative Reward: {ep_reward:.1f}",
        fontsize=11,
        fontweight="bold",
        pad=12
    )

    ax.set_xticks(range(grid_size))
    ax.set_yticks(range(grid_size))
    ax.set_xlabel("Grid Column")
    ax.set_ylabel("Grid Row")

    plt.tight_layout()

    out_file = save_path or (TRAJECTORY_DIR / f"trajectory_seed_{seed}.png")
    plt.savefig(out_file, dpi=200)
    print(f"[+] Rendered trajectory saved to: {out_file}")

    if show_gui:
        try:
            plt.show()
        except Exception:
            pass

    plt.close()
    return out_file, success, steps, ep_reward
